"""Regenerate terminal wide ranges from the pinned Unicode data; no build-time network access."""
import hashlib
from pathlib import Path
from urllib.request import urlopen

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/EastAsianWidth.txt"
SHA256 = "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33"


def main():
    with urlopen(URL, timeout=30) as response:
        data = response.read(1024 * 1024)
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Unicode data checksum mismatch")
    ranges = []
    for line in data.decode("utf-8").splitlines():
        record = line.split("#", 1)[0].strip()
        if not record:
            continue
        code, width = (field.strip() for field in record.split(";"))
        if width not in {"W", "F"}:
            continue
        bounds = code.split("..")
        start, end = int(bounds[0], 16), int(bounds[-1], 16)
        if ranges and start == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], end)
        else:
            ranges.append((start, end))
    root = Path(__file__).resolve().parent.parent
    target = root / "src/SurgeLink.Terminal/CharacterWidth.cs"
    text = target.read_text(encoding="utf-8")
    start = text.index("    // Unicode ")
    end = text.index("    /// <summary>Returns", start)
    generated = (
        f"    // Unicode {VERSION} East_Asian_Width W/F; generated by tools/update-character-width.py.\n"
        f"    // Source: {URL}\n"
        "    // Copyright Unicode, Inc.; see Licenses/Unicode-LICENSE.txt. Ambiguous width stays narrow.\n"
        "    private static readonly (int Start, int End)[] WideRanges =\n    {\n"
        + "".join(f"        (0x{lo:X}, 0x{hi:X}),\n" for lo, hi in ranges)
        + "    };\n\n"
    )
    target.write_text(text[:start] + generated + text[end:], encoding="utf-8", newline="\n")
    print(f"Generated {len(ranges)} Unicode {VERSION} wide ranges")


if __name__ == "__main__":
    main()
